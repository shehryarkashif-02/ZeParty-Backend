export const OFFICIAL_GAME_KEYS = CANONICAL_GAMES.map((g) => g.gameKey);

export function isValidGameId(id) {
  return OFFICIAL_GAME_IDS.includes(id);
}

export function getCanonicalGame(idOrKey) {
  return CANONICAL_GAMES.find((g) => g.id === idOrKey || g.gameKey === idOrKey) || null;
}
